result1 = 2 + 3 * 4
print("2 + 3 * 4 =", result1)  

result2 = (2 + 3) * 4
print("(2 + 3) * 4 =", result2) 

print("\n--- Associativity (Left-to-Right) ---")
result3 = 10 - 4 - 2
print("10 - 4 - 2 =", result3) 

print("\n--- Associativity (Right-to-Left) ---")
result4 = 2 ** 3 ** 2
print("2 ** 3 ** 2 =", result4)
